#!/usr/bin/env node
/**
 * Regenerates lib/placeholders/generated.ts from the project screenshots.
 *
 *   npm run placeholders
 *
 * Every screenshot lib/content.ts points at gets a mosaic: the capture shrunk
 * to one cell per CELL source pixels and squeezed into a 16-colour palette, as
 * a PNG data URI the project window stretches over the frame with
 * image-rendering: pixelated until the real image has decoded. Sixteen colours
 * because that is what a 1993 workstation's 4-bit visual had, and because the
 * palette is most of why six of these come to a couple of kilobytes.
 *
 * The output is a committed file, like lib/github/snapshot.json: nothing
 * generates it at build time, and tests/placeholders.test.ts fails when a
 * screenshot is added, removed or retaken without running this.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "lib", "placeholders", "generated.ts");
/*
 * Source pixels per mosaic cell. 24 turns a 960px capture into 40 columns,
 * which still shows the header bar, the cards and the chart of a dashboard;
 * at 40 it was a dark rectangle with a coloured smudge in it.
 */
const CELL = 24;
const COLOURS = 16;

/*
 * The screenshots the site shows, read from the content file itself. A
 * screenshot is the only thing in it with a `src`; if that stops being true,
 * or one is written some other way, the test that compares this file against
 * PROJECTS is what notices.
 */
const content = readFileSync(join(root, "lib", "content.ts"), "utf8");
const srcs = [...new Set([...content.matchAll(/\bsrc:\s*"([^"]+)"/g)].map((m) => m[1]))].sort();
if (srcs.length === 0) throw new Error("no screenshots found in lib/content.ts");

const mosaics = {};
const sources = {};
for (const src of srcs) {
  const file = join(root, "public", src);
  const bytes = readFileSync(file);
  const { width, height } = await sharp(bytes).metadata();
  const w = Math.max(1, Math.round(width / CELL));
  const h = Math.max(1, Math.round(height / CELL));
  const png = await sharp(bytes)
    .resize(w, h, { fit: "fill", kernel: "lanczos3" })
    .png({ palette: true, colors: COLOURS, dither: 0, compressionLevel: 9, effort: 10 })
    .toBuffer();
  mosaics[src] = `data:image/png;base64,${png.toString("base64")}`;
  sources[src] = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
  process.stderr.write(`${src}: ${width}x${height} -> ${w}x${h}, ${mosaics[src].length} bytes\n`);
}

const entries = (o) =>
  Object.entries(o)
    .map(([k, v]) => `  ${JSON.stringify(k)}:\n    ${JSON.stringify(v)},`)
    .join("\n");

writeFileSync(
  OUT,
  `// generated by scripts/placeholders.mjs - do not edit. Run \`npm run placeholders\`.

/** Each screenshot as a ${COLOURS}-colour mosaic, one cell per ${CELL} source pixels */
export const MOSAICS: Readonly<Record<string, string>> = {
${entries(mosaics)}
};

/** What each mosaic was made from, so a retaken screenshot cannot keep its old mosaic */
export const MOSAIC_SOURCES: Readonly<Record<string, string>> = {
${entries(sources)}
};
`,
);
process.stderr.write(`wrote ${OUT}\n`);
